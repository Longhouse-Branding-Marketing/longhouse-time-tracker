-- Note: PostgreSQL reserves ROLE and TYPE — time_entries uses quoted column names "role" and "type".
-- PostgREST / the app still see them as role and type in JSON.

-- ---------------------------------------------------------------------------
-- Base tables
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.employees (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  person text NOT NULL UNIQUE,
  photo_url text,
  active boolean NOT NULL DEFAULT true,
  start_date date,
  end_date date,
  notes text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.stat_holidays (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  date date NOT NULL,
  holiday_name text NOT NULL,
  jurisdiction text,
  holiday_type text,
  counts_as_working_day boolean NOT NULL DEFAULT false,
  source_url text,
  notes text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.employee_schedules (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  person text NOT NULL REFERENCES public.employees (person) ON UPDATE CASCADE,
  effective_start_date date,
  effective_end_date date,
  monday boolean NOT NULL DEFAULT true,
  tuesday boolean NOT NULL DEFAULT true,
  wednesday boolean NOT NULL DEFAULT true,
  thursday boolean NOT NULL DEFAULT true,
  friday boolean NOT NULL DEFAULT true,
  saturday boolean NOT NULL DEFAULT false,
  sunday boolean NOT NULL DEFAULT false,
  daily_goal numeric NOT NULL DEFAULT 6.5,
  include_in_operations_kpi boolean NOT NULL DEFAULT true,
  notes text,
  created_at timestamptz NOT NULL DEFAULT now(),
  employee_id bigint REFERENCES public.employees (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS public.time_off (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  person text NOT NULL REFERENCES public.employees (person) ON UPDATE CASCADE,
  start_date date NOT NULL,
  end_date date NOT NULL,
  reason text NOT NULL DEFAULT 'Time off',
  counts_as_working_day boolean NOT NULL DEFAULT false,
  notes text,
  created_at timestamptz NOT NULL DEFAULT now(),
  employee_id bigint REFERENCES public.employees (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS public.time_entries (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  person text NOT NULL,
  date date NOT NULL,
  hours numeric NOT NULL,
  department text,
  "role" text,
  task text,
  "type" text,
  billable text,
  comments text,
  source_file text,
  source_row_number integer,
  source_month text,
  source_time_range text,
  source_status text,
  entry_hash text,
  employee_id bigint REFERENCES public.employees (id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS time_entries_entry_hash_key
  ON public.time_entries (entry_hash)
  WHERE entry_hash IS NOT NULL;

