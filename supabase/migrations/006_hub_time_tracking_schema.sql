CREATE OR REPLACE FUNCTION public.time_tracking_user_has_access()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT public.user_can_access_tool_by_slug('time-tracking');
$$;

GRANT EXECUTE ON FUNCTION public.time_tracking_user_has_access() TO authenticated;

