function parseCsv(text) {
  const records = [];
  let row = [];
  let field = "";
  let i = 0;
  let inQuotes = false;
  const src = text.replace(/^\uFEFF/, "");
  const pushField = () => {
    row.push(field);
    field = "";
  };
  const pushRow = () => {
    records.push(row);
    row = [];
  };
  while (i < src.length) {
    const c = src[i];
    if (inQuotes) {
      if (c === '"') {
        if (src[i + 1] === '"') {
          field += '"';
          i += 2;
          continue;
        }
        inQuotes = false;
        i += 1;
        continue;
      }
      field += c;
      i += 1;
      continue;
    }
    if (c === '"') {
      inQuotes = true;
      i += 1;
      continue;
    }
    if (c === ",") {
      pushField();
      i += 1;
      continue;
    }
    if (c === "\n") {
      pushField();
      pushRow();
      i += 1;
      continue;
    }
    if (c === "\r") {
      i += 1;
      continue;
    }
    field += c;
    i += 1;
  }
  if (field.length || row.length) {
    pushField();
    pushRow();
  }
  return records.filter((r) => r.some((cell) => cell.trim() !== ""));
}

function sheet(name) {
  const records = parseCsv(readFileSync(join(dataDir, name), "utf8"));
  const headerIndex = records.findIndex((row) => row[0] && !row[0].startsWith("Table"));
  const headers = records[headerIndex];
  return records.slice(headerIndex + 1).map((row) => {
    const obj = {};
    headers.forEach((header, index) => {
      if (!header) return;
      obj[header] = row[index] ?? "";
    });
    return obj;
  });
}

function sqlString(value) {
  if (value == null || value === "") return "NULL";
  return `'${String(value).replaceAll("'", "''")}'`;
}

