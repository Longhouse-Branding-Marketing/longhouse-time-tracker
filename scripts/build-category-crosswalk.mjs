function insert(table, columns, rows) {
  const chunk = 80;
  for (let i = 0; i < rows.length; i += chunk) {
    const slice = rows.slice(i, i + chunk);
    lines.push(
      `INSERT INTO public.${table} (${columns.join(", ")}) VALUES`
    );
    lines.push(slice.map((row) => `  (${row.join(", ")})`).join(",\n") + ";");
    lines.push(``);
  }
}

